import random
import math
import numpy as np
import matplotlib.pyplot as plt
from dataclasses import dataclass

# Reproducible results
random.seed(42)
np.random.seed(42)

GRID_SIZE = 20
NUM_WAYPOINTS = 6
POPULATION_SIZE = 40
GENERATIONS = 100
MUTATION_RATE = 0.15
MAX_RANGE = 45.0
TOURNAMENT_SIZE = 3

START = (0, 0)

# Simulated no-fly zones and hazardous cells
NO_FLY = {(5, 5), (5, 6), (6, 5), (12, 12), (12, 13)}
HAZARDS = {(x, y) for x in range(8, 12)
           for y in range(3, 7)}

# Important disaster-zone targets
TARGETS = [(3, 8), (8, 12), (15, 5),
           (16, 15), (6, 16), (13, 9)]


@dataclass
class Chromosome:
    waypoints: list
    speeds: list
    sensors: list


class UAVGeneticAlgorithm:

    def __init__(self):
        self.population = [
            self.create_chromosome()
            for _ in range(POPULATION_SIZE)
        ]
        self.best_history = []
        self.average_history = []
        self.random_best = None

    def create_chromosome(self):
        """Create a random candidate drone route."""
        points = [
            (random.randint(1, GRID_SIZE - 2),
             random.randint(1, GRID_SIZE - 2))
            for _ in range(NUM_WAYPOINTS)
        ]
        speeds = [random.randint(1, 4)
                  for _ in range(NUM_WAYPOINTS)]
        sensors = [random.randint(0, 1)
                   for _ in range(NUM_WAYPOINTS)]
        return Chromosome(points, speeds, sensors)

    def repair(self, chromosome):
        """Keep all waypoint coordinates inside the grid."""
        chromosome.waypoints = [
            (max(0, min(GRID_SIZE - 1, int(x))),
             max(0, min(GRID_SIZE - 1, int(y))))
            for x, y in chromosome.waypoints
        ]
        chromosome.speeds = [
            max(1, min(4, int(s)))
            for s in chromosome.speeds
        ]
        chromosome.sensors = [
            1 if s else 0 for s in chromosome.sensors
        ]
        return chromosome

    def route(self, chromosome):
        return [START] + chromosome.waypoints

    def fitness(self, chromosome):
        route = self.route(chromosome)
        distance = 0.0
        hazard_cost = 0.0
        penalty = 0.0
        covered_targets = set()
        detected_targets = set()

        # Evaluate every route segment
        for i in range(1, len(route)):
            x1, y1 = route[i - 1]
            x2, y2 = route[i]
            segment_distance = math.dist(
                (x1, y1), (x2, y2)
            )
            distance += segment_distance

            # Approximate intermediate path cells
            steps = max(1, math.ceil(segment_distance * 2))
            for k in range(steps + 1):
                t = k / steps
                x = round(x1 + t * (x2 - x1))
                y = round(y1 + t * (y2 - y1))

                if (x, y) in NO_FLY:
                    penalty += 20
                if (x, y) in HAZARDS:
                    hazard_cost += 1

        # Check target coverage and sensor detection
        for i, (x, y) in enumerate(chromosome.waypoints):
            for j, (tx, ty) in enumerate(TARGETS):
                d = math.dist((x, y), (tx, ty))
                if d <= 4:
                    covered_targets.add(j)
                if d <= 3 and chromosome.sensors[i] == 1:
                    detected_targets.add(j)

        if distance > MAX_RANGE:
            penalty += 5 * (distance - MAX_RANGE)

        # Faster speed reduces travel time but costs more energy
        travel_time = sum(
            math.dist(route[i], route[i + 1]) /
            chromosome.speeds[i]
            for i in range(NUM_WAYPOINTS)
        )
        energy = sum(
            math.dist(route[i], route[i + 1]) *
            (1 + 0.15 * chromosome.speeds[i] ** 2)
            for i in range(NUM_WAYPOINTS)
        )

        coverage = len(covered_targets) / len(TARGETS)
        detection = len(detected_targets) / len(TARGETS)
        energy_norm = energy / 200
        time_norm = travel_time / 50
        hazard_norm = hazard_cost / 20

        score = (
            5 * coverage
            + 4 * detection
            - 2 * energy_norm
            - 2 * time_norm
            - 5 * hazard_norm
            - 10 * penalty
        )
        return score

    def select_parent(self):
        group = random.sample(
            self.population,
            TOURNAMENT_SIZE
        )
        return max(group, key=self.fitness)

    def crossover(self, p1, p2):
        """Swap route segments and matching controls."""
        cut = random.randint(1, NUM_WAYPOINTS - 1)

        child1 = Chromosome(
            p1.waypoints[:cut] + p2.waypoints[cut:],
            p1.speeds[:cut] + p2.speeds[cut:],
            p1.sensors[:cut] + p2.sensors[cut:]
        )
        child2 = Chromosome(
            p2.waypoints[:cut] + p1.waypoints[cut:],
            p2.speeds[:cut] + p1.speeds[cut:],
            p2.sensors[:cut] + p1.sensors[cut:]
        )
        return self.repair(child1), self.repair(child2)

    def mutate(self, chromosome):
        """Change a coordinate, speed or sensor state."""
        for i in range(NUM_WAYPOINTS):
            if random.random() < MUTATION_RATE:
                x, y = chromosome.waypoints[i]
                x += random.randint(-3, 3)
                y += random.randint(-3, 3)
                chromosome.waypoints[i] = (x, y)

            if random.random() < MUTATION_RATE:
                chromosome.speeds[i] = random.randint(1, 4)

            if random.random() < MUTATION_RATE:
                chromosome.sensors[i] = 1 - chromosome.sensors[i]

        return self.repair(chromosome)

    def run(self):
        for generation in range(GENERATIONS):
            scores = [self.fitness(c)
                      for c in self.population]
            best_index = int(np.argmax(scores))

            self.best_history.append(scores[best_index])
            self.average_history.append(float(np.mean(scores)))

            # Elitism: retain the best solution
            new_population = [
                self.population[best_index]
            ]

            while len(new_population) < POPULATION_SIZE:
                p1 = self.select_parent()
                p2 = self.select_parent()
                c1, c2 = self.crossover(p1, p2)

                new_population.append(self.mutate(c1))
                if len(new_population) < POPULATION_SIZE:
                    new_population.append(self.mutate(c2))

            self.population = new_population

        best = max(self.population, key=self.fitness)
        self.random_best = max(
            (self.create_chromosome() for _ in range(2000)),
            key=self.fitness
        )
        return best


def plot_results(ga, best):
    # 1. Fitness convergence
    plt.figure(figsize=(8, 5))
    plt.plot(ga.best_history, label="Best Fitness")
    plt.plot(ga.average_history, label="Average Fitness")
    plt.xlabel("Generation")
    plt.ylabel("Fitness")
    plt.title("GA Fitness Convergence")
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.savefig("fitness_convergence.png")
    plt.show()

    # 2. Evolved UAV route
    plt.figure(figsize=(8, 7))
    for x, y in NO_FLY:
        plt.scatter(x, y, marker="s", s=100,
                    label="No-fly zone" if (x, y) == min(NO_FLY)
                    else None)
    for x, y in HAZARDS:
        plt.scatter(x, y, marker="s", s=60,
                    label="Hazard" if (x, y) == min(HAZARDS)
                    else None)

    tx, ty = zip(*TARGETS)
    plt.scatter(tx, ty, marker="*", s=150,
                label="Targets")

    route = [START] + best.waypoints
    rx, ry = zip(*route)
    plt.plot(rx, ry, "-o", label="Best UAV route")
    plt.scatter(*START, marker="D", s=100, label="Start")

    plt.xlim(-1, GRID_SIZE)
    plt.ylim(-1, GRID_SIZE)
    plt.xlabel("X coordinate")
    plt.ylabel("Y coordinate")
    plt.title("Evolved UAV Flight Path")
    plt.grid(True)
    plt.legend()
    plt.tight_layout()
    plt.savefig("uav_route.png")
    plt.show()

    # 3. Target coverage heatmap
    heat = np.zeros((GRID_SIZE, GRID_SIZE))
    for x, y in best.waypoints:
        heat[max(0, y - 4):min(GRID_SIZE, y + 5),
             max(0, x - 4):min(GRID_SIZE, x + 5)] += 1

    plt.figure(figsize=(8, 6))
    plt.imshow(heat, origin="lower", cmap="hot")
    plt.colorbar(label="Coverage intensity")
    plt.xlabel("X coordinate")
    plt.ylabel("Y coordinate")
    plt.title("UAV Coverage Heatmap")
    plt.tight_layout()
    plt.savefig("coverage_heatmap.png")
    plt.show()


if __name__ == "__main__":
    ga = UAVGeneticAlgorithm()
    best = ga.run()

    print("Best GA fitness:", round(ga.fitness(best), 3))
    print("Random-search fitness:",
          round(ga.fitness(ga.random_best), 3))
    print("Best waypoints:", best.waypoints)
    print("Speeds:", best.speeds)
    print("Sensors:", best.sensors)

    plot_results(ga, best)

